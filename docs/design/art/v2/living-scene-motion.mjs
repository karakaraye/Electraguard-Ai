// Motion for the living polling-day scene: one 36-second loop, written as a timeline and turned
// into CSS keyframes. Run from the repository root:  node docs/design/art/v2/living-scene-motion.mjs
// Output: frontend/app/(public)/_components/living-scene/scene-motion.css
//
// The base styles (no animation) are the still frame used for reduced motion and low-power phones:
// the voter at the ballot box, the paper above the slot, everyone else standing.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const LOOP = 36;
const pct = (t) => `${Math.max(0, Math.min(100, (t / LOOP) * 100)).toFixed(3)}%`;
const r1 = (v) => Math.round(v * 10) / 10;

/** A path of [time, x, y?, opacity?] stops; holds between stops are explicit, so movement is linear only where written. */
function moveKeyframes(name, stops) {
  const body = stops
    .map(([t, x, y = 0, o = 1]) => `${pct(t)}{transform:translate(${r1(x)}px,${r1(y)}px);opacity:${o}}`)
    .join("");
  return `@keyframes ${name}{${body}}`;
}

/** Alternating leg poses (and arm swing) inside walking windows; standing pose elsewhere. */
function stepKeyframes(name, windows, half = 0.42) {
  const a = [`0%{opacity:1}`];
  const b = [`0%{opacity:0}`];
  const arm = [`0%{transform:rotate(0deg)}`];
  for (const [from, to] of windows) {
    let k = 0;
    for (let t = from; t < to - 0.05; t += half, k++) {
      const stride = k % 2 === 0;
      a.push(`${pct(t)}{opacity:${stride ? 0 : 1}}`);
      b.push(`${pct(t)}{opacity:${stride ? 1 : 0}}`);
      arm.push(`${pct(t)}{transform:rotate(${stride ? 10 : -8}deg)}`);
    }
    a.push(`${pct(to)}{opacity:1}`);
    b.push(`${pct(to)}{opacity:0}`);
    arm.push(`${pct(to)}{transform:rotate(0deg)}`);
  }
  a.push(`100%{opacity:1}`);
  b.push(`100%{opacity:0}`);
  arm.push(`100%{transform:rotate(0deg)}`);
  return `@keyframes ${name}-a{${a.join("")}}@keyframes ${name}-b{${b.join("")}}@keyframes ${name}-arm{${arm.join("")}}`;
}


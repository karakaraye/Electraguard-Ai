// Full loop, only when motion is allowed and the scene is in full-motion mode.
let loop = "";
for (const [id, p] of Object.entries(people)) {
  loop += moveKeyframes(`ls-${id}`, p.move) + stepKeyframes(`ls-${id}-legs`, p.walk);
  loop += `.living-scene[data-motion="full"] #ls-${id}{animation:ls-${id} ${LOOP}s linear infinite}`;
  loop += `.living-scene[data-motion="full"] #ls-${id} .lg-a{animation:ls-${id}-legs-a ${LOOP}s step-end infinite}`;
  loop += `.living-scene[data-motion="full"] #ls-${id} .lg-b{animation:ls-${id}-legs-b ${LOOP}s step-end infinite}`;
  loop += `.living-scene[data-motion="full"] #ls-${id} .arm{animation:ls-${id}-legs-arm ${LOOP}s linear infinite}`;
}
const qMove = [[0, 0], [12, 0], [12.5, 9], [13.6, 9], [14.6, 0], [36, 0]];
loop += moveKeyframes("ls-queue", qMove) + stepKeyframes("ls-queue-legs", [[12, 12.84]]);
queue.forEach((id, i) => {
  const d = `${(i * 0.08).toFixed(2)}s`;
  loop += `.living-scene[data-motion="full"] #ls-${id}{animation:ls-queue ${LOOP}s ease-in-out infinite ${d}}`;
  loop += `.living-scene[data-motion="full"] #ls-${id} .lg-a{animation:ls-queue-legs-a ${LOOP}s step-end infinite ${d}}`;
  loop += `.living-scene[data-motion="full"] #ls-${id} .lg-b{animation:ls-queue-legs-b ${LOOP}s step-end infinite ${d}}`;
});
// The wheel turns while the wheelchair rolls with the queue.
loop += `@keyframes ls-wheel{0%,33.33%{transform:rotate(0)}34.7%{transform:rotate(38deg)}37.8%{transform:rotate(38deg)}40.6%,100%{transform:rotate(0)}}`;
loop += `.living-scene[data-motion="full"] #ls-q5 .wheel{animation:ls-wheel ${LOOP}s ease-in-out infinite .32s}`;
// The child waves twice.
loop += `@keyframes ls-wave{0%,38.9%{transform:rotate(0)}39.7%{transform:rotate(-26deg)}40.5%{transform:rotate(-4deg)}41.3%{transform:rotate(-26deg)}42.2%,100%{transform:rotate(0)}}`;
loop += `.living-scene[data-motion="full"] #ls-child .wave{animation:ls-wave ${LOOP}s ease-in-out infinite}`;
// Card reader blinks green as the voter is accredited.
loop += `@keyframes ls-led{0%,33.3%{fill:var(--ls-c3)}33.6%,35%{fill:var(--ok-solid)}35.3%,100%{fill:var(--ls-c3)}}`;
loop += `.living-scene[data-motion="full"] .led{animation:ls-led ${LOOP}s step-end infinite}`;
// The ballot paper appears over the slot and slides in.
loop += `@keyframes ls-ballot{0%,45.8%{opacity:0;transform:translateY(0)}46.4%{opacity:1;transform:translateY(0)}48.6%{opacity:1;transform:translateY(0)}50.4%{opacity:0;transform:translateY(16px)}100%{opacity:0;transform:translateY(16px)}}`;
loop += `.living-scene[data-motion="full"] .ballot{animation:ls-ballot ${LOOP}s ease-in infinite}`;
// The observer's report: dotted path draws, the card travels up it, a tick appears, all fade.
loop += `@keyframes ls-rpath{0%,59.7%{opacity:0;stroke-dashoffset:120}60.3%{opacity:1;stroke-dashoffset:120}65.3%{opacity:1;stroke-dashoffset:0}80.5%{opacity:1;stroke-dashoffset:0}83.3%,100%{opacity:0;stroke-dashoffset:0}}`;
loop += `@keyframes ls-rcard{0%,59.7%{opacity:0;transform:translate(0,0)}60.3%{opacity:1;transform:translate(0,0)}62.5%{opacity:1;transform:translate(34px,-72px)}65.3%{opacity:1;transform:translate(104px,-132px)}66%,100%{opacity:0;transform:translate(104px,-132px)}}`;
loop += `@keyframes ls-tick{0%,65%{opacity:0;transform:scale(.8)}66.7%{opacity:1;transform:scale(1)}80.5%{opacity:1;transform:scale(1)}83.3%,100%{opacity:0;transform:scale(1)}}`;
loop += `.living-scene[data-motion="full"] .rpath{animation:ls-rpath ${LOOP}s linear infinite}`;
loop += `.living-scene[data-motion="full"] .rcard{animation:ls-rcard ${LOOP}s cubic-bezier(.77,0,.175,1) infinite}`;
loop += `.living-scene[data-motion="full"] .tick{animation:ls-tick ${LOOP}s cubic-bezier(.23,1,.32,1) infinite}`;

// Ambient movement: runs in full and ambient modes. Each person breathes on a 4 s cycle from a different start.
let ambient = `@keyframes ls-breathe{0%,100%{transform:translateY(0)}50%{transform:translateY(-0.9px)}}`;
ambient += `@keyframes ls-sway{0%,100%{transform:rotate(-1.2deg)}50%{transform:rotate(1.2deg)}}`;

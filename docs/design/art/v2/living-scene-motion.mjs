ambient += `@keyframes ls-birds{0%,5.5%{opacity:0;transform:translate(260px,10px)}6.5%{opacity:1;transform:translate(300px,8px)}21%{opacity:1;transform:translate(820px,-26px)}22%,61%{opacity:0;transform:translate(860px,-28px)}62%{opacity:1;transform:translate(300px,4px)}77%{opacity:1;transform:translate(820px,-30px)}78%,100%{opacity:0;transform:translate(860px,-30px)}}`;
const ids = ["voter", "q2", "q3", "q4", "q5", "q6", "child", "q7", "q8", "w1", "w2", "w3", "d1", "d2", "obs"];
ids.forEach((id, i) => {
  ambient += `.living-scene:not([data-motion="still"]) #ls-${id} .bob{animation:ls-breathe 4s ease-in-out infinite -${((i * 0.73) % 4).toFixed(2)}s}`;
});

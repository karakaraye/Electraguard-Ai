ambient += `.living-scene:not([data-motion="still"]) .palm:nth-of-type(2) .fronds{animation:ls-sway 7s ease-in-out infinite -3.4s}`;
ambient += `.living-scene:not([data-motion="still"]) .palm:nth-of-type(3) .fronds{animation:ls-sway 6.5s ease-in-out infinite -5s}`;
ambient += `.living-scene:not([data-motion="still"]) .crown{animation:ls-crown 7s ease-in-out infinite}`;
ambient += `.living-scene:not([data-motion="still"]) .birds{animation:ls-birds ${LOOP}s linear infinite}`;
ambient += `.living-scene .birds{opacity:0}`;
// Evening: the lamps come on one after another, once, when the footer scene starts.
ambient += `@keyframes ls-lamp{from{opacity:0}to{opacity:1}}`;
[1, 2, 3].forEach((i) => {
  ambient += `.living-scene[data-variant="evening"]:not([data-motion="still"]) .lamp-${i}{animation:ls-lamp .9s cubic-bezier(.23,1,.32,1) both ${(0.3 + (i - 1) * 0.8).toFixed(1)}s}`;
});

css += `@media (prefers-reduced-motion: no-preference){\n${loop}\n${ambient}\n}\n`;
// Everything stops while the scene is off-screen or the tab is hidden.
css += `.living-scene[data-paused] *{animation-play-state:paused!important}\n`;

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../../frontend/app/(public)/_components/living-scene/scene-motion.css");
writeFileSync(out, css);
